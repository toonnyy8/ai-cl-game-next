#!/usr/bin/env python3
"""run.py — plays trials.lisp in the native sim (tools/simgate/trial.lisp, in chunks over processes) and writes results.json and
results.md: per trial both sides' damage, the hits in order (side, move, result, base damage), the cancels, the first real hit, the
free frames, the end distance (PLAN4 step 2, Hisagi's catalogue).

  python3 docs/research/strategy-drsi/sp/kits/hisagi/run.py [-j 12] [--out results]     (gen.py first)
"""
import json, os, re, sys, tempfile
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '../../../../../../tools'))
import simlib  # noqa: E402

HIT = re.compile(r'\] (P[12]) (\S+) -> (P[12]) (\S+) (-?\d+)')
CANCEL = re.compile(r'\] (P[12]) (.+?) x (P[12]): (CANCEL|ABSORBED)')
TAGS = re.compile(r'\] (P[12]) (BREAK fs|STEAL fs|KIN on|BIND EVEN|BIND START|BIND END|HODEN|ZANDEN|refused)')

def run_chunk(lines):
    with tempfile.NamedTemporaryFile('w', suffix='.lisp', delete=False, dir=os.path.join(simlib.ROOT, 'build')) as f:
        f.write('\n'.join(lines) + '\n'); p = f.name
    try:
        r = simlib.run_lisp('simgate/trial.lisp', [p])
    finally:
        os.unlink(p)
    if r.returncode:
        sys.exit((r.stdout + r.stderr)[-3000:] + f'\n[run.py] exited {r.returncode}')
    return r.stdout

def parse(out):
    res, cur = [], None
    for line in out.splitlines():
        if 'trial begin ' in line:
            cur = {'hits': [], 'cancels': [], 'tags': [], 'name': line.split('trial begin ', 1)[1].strip()}
        elif 'trial end ' in line and cur is not None:
            f = [x.strip() for x in line.split('trial end ', 1)[1][len(cur['name']):].split('|')]   # (a name may hold '|')
            kv = {x.split(' ', 1)[0]: (x.split(' ', 1)[1] if ' ' in x else '') for x in f[1:]}
            more = kv.get('more', '')
            m = re.search(r'self ([+-]\d+)', more)
            cur.update(p2dmg=int(kv['dmg']), p1dmg=-int(m.group(1)) if m else 0, adv=kv['adv'], dist=float(kv['dist']),
                       fs=kv['fs'], free=kv['free'], konpaku=kv.get('konpaku', ''), more=more)
            real = [h for h in cur['hits'] if h[3] in ('HIT', 'COUNTER')]
            cur['first'] = (real[0][0] + ' ' + real[0][1]) if real else 'none'
            res.append(cur); cur = None
        elif cur is not None:
            m = HIT.search(line)
            if m:
                fr = int(re.search(r'\[\s*(\d+)\]', line).group(1))
                cur['hits'].append((m[1], m[2], fr, m[4], int(m[5])))
                continue
            m = CANCEL.search(line)
            if m:
                cur['cancels'].append(f'{m[1]} {m[2]} {m[4]}')
                continue
            m = TAGS.search(line)
            if m:
                cur['tags'].append(line.split('] ', 1)[1].strip())
    return res

def main():
    a = sys.argv[1:]
    j = int(a[a.index('-j') + 1]) if '-j' in a else 12
    out = a[a.index('--out') + 1] if '--out' in a else 'results'
    src = a[a.index('--file') + 1] if '--file' in a else os.path.join(HERE, 'trials.lisp')
    simlib.build()
    lines = [l for l in open(src) if l.startswith('(:name')]
    k = max(1, (len(lines) + j - 1) // j)
    chunks = [lines[i:i + k] for i in range(0, len(lines), k)]
    res = [t for o in simlib.pool(run_chunk, chunks, j) for t in parse(o)]
    assert len(res) == len(lines), (len(res), len(lines))
    json.dump(res, open(os.path.join(HERE, out + '.json'), 'w'), indent=0)
    with open(os.path.join(HERE, out + '.md'), 'w') as f:
        f.write('<!-- generated by run.py from trials.lisp -->\n\n| Trial | his dmg | Hisagi dmg | first real hit | cancels | adv | dist | FS | hits (side move frame result base) | tags |\n|---|---|---|---|---|---|---|---|---|---|\n')
        for t in res:
            f.write(f"| {t['name'].replace('|', ' · ')} | {t['p2dmg']} | {t['p1dmg']} | {t['first']} | {'; '.join(t['cancels']) or '—'} | {t['adv']} | {t['dist']:.2f} | {t['fs']} | "
                    f"{'; '.join(f'{h[0]} {h[1]} f{h[2]} {h[3]} {h[4]}' for h in t['hits']) or '—'} | {'; '.join(t['tags'])} |\n")
    print(len(res), 'trials ->', out + '.md / .json')

if __name__ == '__main__':
    main()
